"""LAKVPipeline.run(question, receiver_question=None): default behavior must be byte-identical.

CPU only, UNTESTED ON GPU. The golden file tests/fixtures/run_prompts_golden.json was generated by
running tests/prompt_harness.py against the UNMODIFIED pipeline (a worktree of exp/consolidate-v9,
where run() has no receiver_question parameter). Only prompts are compared with the golden file.
"""
import json
from pathlib import Path

import pytest

import prompt_harness as h
from lakv.pipeline import LAKVPipeline

GOLDEN = json.loads((Path(__file__).parent / "fixtures" / "run_prompts_golden.json").read_text(encoding="utf-8"))
CASES = {"hotpotqa_visible": (h.BLOB, "hotpotqa", True),
         "hotpotqa_nopass": (h.BLOB, "hotpotqa", False),
         "gsm8k_plain": (h.GSM, "gsm8k", True)}


@pytest.fixture(scope="module")
def model():
    return h.tiny_model()


@pytest.mark.parametrize("name", list(CASES))
@pytest.mark.parametrize("explicit_none", [False, True])
def test_prompts_are_byte_identical_to_the_unmodified_pipeline(model, name, explicit_none):
    q, ds, rsp = CASES[name]
    kwargs = {"receiver_question": None} if explicit_none else None
    got = h.record(model, q, ds, rsp, run_kwargs=kwargs)
    want = GOLDEN["cases"][name]
    assert got["chat_calls"] == want["chat_calls"]   # every message list handed to the chat template
    assert got["id_calls"] == want["id_calls"]       # every token-id list the model receives


def test_default_and_explicit_none_give_identical_generation(model):
    a = h.record(model, h.BLOB)
    b = h.record(model, h.BLOB, run_kwargs={"receiver_question": None})
    assert a == b


def test_golden_file_really_comes_from_the_unmodified_pipeline():
    assert "UNMODIFIED" in GOLDEN["source"] and set(GOLDEN["cases"]) == set(CASES)


def test_receiver_question_replaces_only_the_receivers_user_content(model):
    view = "Context:\n[Beta County] Beta County is a county. Its seat is Alpha Town.\n\nQuestion: In which county is Alpha Town?"
    got = h.record(model, h.BLOB, run_kwargs={"receiver_question": view})
    base = h.record(model, h.BLOB)
    c, b = got["chat_calls"], base["chat_calls"]
    assert c[0] == b[0]                                      # sender (agent 0): unchanged, sees everything
    for agent in (1, 2):
        assert c[agent][0] == b[agent][0]                    # system prompt unchanged
        assert c[agent][-1] == {"role": "user", "content": view}
        assert b[agent][-1] == {"role": "user", "content": h.BLOB}
    assert got["id_calls"][0] == base["id_calls"][0]
    assert got["id_calls"][1] != base["id_calls"][1] and len(got["id_calls"][1]) < len(base["id_calls"][1])


def test_question_only_receiver_question_equals_the_nopass_prompts(model):
    # the _hide100 alias relies on this: the all-hidden view is exactly what _nopass sends
    qo = LAKVPipeline._question_only(h.BLOB)
    via_arg = h.record(model, h.BLOB, run_kwargs={"receiver_question": qo})
    nopass = h.record(model, h.BLOB, receiver_sees_passages=False)
    assert via_arg["chat_calls"] == nopass["chat_calls"] and via_arg["id_calls"] == nopass["id_calls"]


def test_receiver_question_conflicts_with_nopass(model):
    with pytest.raises(ValueError, match="receiver_question"):
        h.record(model, h.BLOB, receiver_sees_passages=False, run_kwargs={"receiver_question": "x"})
